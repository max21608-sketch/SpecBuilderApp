-- ---- 5. the type suggestion's words (B) -----------------------------------
--
-- On his types, because the two sheets that cover several of them are where a
-- suggestion is needed: `armchairs-benches-stools-sofas` (S, A, B) and
-- `sofas-bed-daybeds` (S, D). Whole words, matched by src/lib/matrix-type.ts:
-- the longest phrase wins over one inside it ("bar stool" over "stool"), two
-- types named at once abstain ("Sofa bench"), and a name naming none takes
-- the sheet's default. 0005 never writes these columns, so a re-seed of it
-- leaves them alone. Claude's best guess (decision B), Matthew to confirm.
update spec_matrix_categories set suggest_words = v.words, updated_by = 'seed'
  from (values
    ('S', array['sofa', 'settee', 'loveseat']),
    ('B', array['bench', 'stool']),
    ('D', array['daybed', 'chaise']),
    ('A', array['bar stool', 'counter stool'])
  ) as v(code, words)
 where spec_matrix_categories.code = v.code
   and spec_matrix_categories.suggest_words is distinct from v.words;

-- An armchair is what the armchairs sheet holds when the name says nothing
-- else ("Lobby armchair", "Lounge chair"). Cleared first so the one-default
