-- ==========================================================================
-- 0014_cabinetry_gate_model.sql
--
-- A PROVISIONAL CABINETRY GATE MODEL, DRAFTED BY AI ON 20 NOV 2026, NOT YET
-- CONFIRMED BY MATTHEW. Every row below says so, and so does every screen that
-- reads one (spec_matrix_categories.provisional_note, 0061).
--
-- WHY. Matthew's matrix (db/seed/0006) covers his nine seating categories.
-- The eight cabinetry cheat sheets had no gate model, so a blank side table
-- fell back to the 0019 placeholder and asked 30 questions before it could be
-- priced. Matthew, 2026-09-19 (matrix-assumptions.md Q9): "You could probably
-- draft one to go in its place for now." Max, 2026-11-20: "try and create a
-- gate model and just note that it was generated by AI." The draft, its
-- reasoning and its weak points are docs/plans/chase-decisions-2026-11-20.md
-- section A; the build's design is the chase-build design, Track 1 Stage 1.
--
-- WHAT IS HERE, in order:
--
--   1. Eight matrix TYPES, one per cabinetry cheat sheet, family `cabinetry`,
--      carrying the provisional sentence. Keyed on `code`.
--   2. Eight MAP rows, one sheet each, so no union widens anything.
--   3. Rows 101-121 of spec_field_gates, in 0006's column list, keyed on
--      `matrix_row`. His "All categories" rows (1-6, 8-11, 32-35) reach the
--      new types through the GENERATED applies_to_all (0061), so NOTHING
--      HERE EDITS HIS ROWS and a re-seed of 0006 cannot flip-flop with this.
--   4. 77 checklist questions, so every row that reaches a cabinetry type can
--      be answered: 41 BWS-field questions the sheets never asked (Assembly
--      guide, Purchasing notes, Timber finish 2/3, Metal finish 2 on seven,
--      Outdoor on the four sheets that lacked it), worded byte-for-byte as
--      0007 words them, and 36 readiness questions -- the four yes/no
--      CONTROLLERS (101-104), lighting spec (119) and socket / wire access
--      (120). Keyed on (category, seed_key) like every requirement seed.
--   5. The type SUGGESTION's words (B): which words in an item's name suggest
--      which of his types within a sheet covering several, and the default.
--   6. Closing checks that raise.
--
-- THREE DEVIATIONS FROM THE DECISIONS TABLE, each because the table as
-- written would fail or lie:
--
--   * Row 103 (integrated lighting or power) is asked of ALL EIGHT types,
--     dining tables included. Row 120 (socket / wire access) reaches dining
--     tables and depends on 103; a dining table not asked 103 would read
--     `unknown` on row 120 for ever and never clear TG0.
--   * The controllers are NEW readiness questions, not the sheets' own
--     "Any Specialist Lighting/ Power Required?". 0057's trigger refuses a
--     `local_key` on a row somebody has answered, and an answer to the old
--     question does not answer the new one. Both stay on the checklist.
--   * Substrate, Runners and Hinges are `free_text`. BWS keeps a substrate
--     list and a runners list (captured read-only 2026-09-22,
--     docs/plans/bws-palette-capture-2026-09-22.json) that this app does not
--     hold, and hinges are free text in BWS itself. `palette_raw` says so.
--     No palette is invented (FMT-GEN-01).
--
-- `tgq_levels` is all three levels on every new question, the 0019 default.
-- On a mapped category nothing reads it -- the gate rows decide TGQ -- and it
-- is written only so the column means what it means everywhere else.
--
-- Re-seeding is safe: every insert upserts on its key, nothing is deleted,
-- and the four columns 0057 guards are written only with the values a row
-- was born with.
-- ==========================================================================

