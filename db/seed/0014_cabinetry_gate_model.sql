update spec_matrix_category_map m set suggest_default = false, updated_by = 'seed'
 where m.suggest_default
   and not (m.matrix_code = 'A'
            and m.item_category_id = (select id from item_categories where slug = 'armchairs-benches-stools-sofas'));
