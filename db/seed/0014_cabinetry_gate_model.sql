-- ---- 6. closing checks ----------------------------------------------------
do $$
declare bad text;
begin
  -- Every row names a field or a key: a json id spec_fields does not hold
  -- would arrive here as neither.
  select string_agg(matrix_row::text, ', ') into bad
    from spec_field_gates where spec_field_id is null and local_key is null;
  if bad is not null then
    raise exception '0014 seed: gate row(s) % name a BWS id that spec_fields does not hold', bad;
  end if;

  -- Every FIELD row is answerable by every category it reaches. A gate over a
  -- field the checklist cannot ask reads `unanswerable` and nobody can pass it.
  select string_agg(distinct format('%s on %s', g.matrix_row, c.slug), '; ') into bad
    from spec_field_gates g
    join spec_matrix_category_map m on g.applies_to_all or g.applies_to && array[m.matrix_code]
    join item_categories c on c.id = m.item_category_id
   where g.spec_field_id is not null
     and not exists (select 1 from requirements r where r.category_id = c.id and r.spec_field_id = g.spec_field_id);
  if bad is not null then
    raise exception '0014 seed: gate rows reach a category whose checklist cannot ask them: %', bad;
  end if;

  -- Every drafted LOCAL-KEY row is answerable by every category it reaches.
  select string_agg(distinct format('%s on %s', g.matrix_row, c.slug), '; ') into bad
    from spec_field_gates g
    join spec_matrix_category_map m on g.applies_to && array[m.matrix_code]
    join item_categories c on c.id = m.item_category_id
   where g.matrix_row between 101 and 121 and g.local_key is not null
     and not exists (select 1 from requirements r where r.category_id = c.id and r.local_key = g.local_key);
  if bad is not null then
    raise exception '0014 seed: drafted rows reach a category with no question for their key: %', bad;
  end if;

  -- Every conditional's controller is a TGQ row asked of every type its
  -- dependent reaches, or the dependent reads `unknown` for ever there.
  select string_agg(format('%s for %s', d.matrix_row, code), ', ') into bad
    from spec_field_gates d
    cross join lateral unnest(d.applies_to) as code
   where d.conditional_on_key is not null
     and not exists (
       select 1 from spec_field_gates c
        where c.local_key = d.conditional_on_key and c.gate = 'TGQ'
          and (c.applies_to_all or code = any(c.applies_to)));
  if bad is not null then
    raise exception '0014 seed: a conditional row reaches a type its controller is not asked of: %', bad;
  end if;

  -- Every drafted row and type says what it is.
  select string_agg(matrix_row::text, ', ') into bad
    from spec_field_gates
   where matrix_row between 101 and 121
     and position('Provisional cabinetry gate model, drafted by AI on 20 Nov 2026, not yet confirmed by Matthew' in coalesce(notes, '')) <> 1;
  if bad is not null then
    raise exception '0014 seed: drafted gate row(s) % do not carry the provisional sentence', bad;
  end if;
end $$;
